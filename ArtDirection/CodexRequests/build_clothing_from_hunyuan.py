# Garment-only envelopes around a standard adult standing at origin.  The fitting
# session supplies the actual MetaHuman body, conforming and skin weights.
PIECE_SETUP = {
    # The first fitter import measured the raw Hunyuan upper at ~1.45x scale
    # and 55 cm too high.  These envelopes are corrected to the proxy space.
    "Upper": (1.00, 0.35),
    "Lower": (0.72, 0.00),
    "Feet": (0.45, 0.00),
    "Helmet": (0.235, 1.00),
}
BODY_REFERENCE = "Standard adult MetaHuman Medium/NormalWeight A-pose proxy at ground origin (body not exported)"


def select_only(obj):
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj


def clear_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    for mesh in list(bpy.data.meshes):
        bpy.data.meshes.remove(mesh)


def make_materials(side_dir, stem):
    ref = side_dir / "References" / f"{stem}.png"
    tex_dir = side_dir / "Textures"
    tex_dir.mkdir(parents=True, exist_ok=True)
    tex_path = tex_dir / f"T_{stem}_BaseColor.png"
    image = bpy.data.images.load(str(ref), check_existing=False)
    image.scale(1024, 1024)
    image.filepath_raw = str(tex_path)
    image.file_format = "PNG"
    image.save()
    side = side_dir.name
    tint = (0.40, 0.025, 0.02, 1) if side == "Giltside" else (0.55, 0.63, 0.68, 1)
    metal = (0.13, 0.085, 0.04, 1) if side == "Giltside" else (0.42, 0.49, 0.55, 1)

    # Plain-redo garments deliberately use a uniform, full-coverage map.  The
    # fitter reported white gaps from projection UVs; a solid map preserves the
    # requested simple look without any unpainted islands.
    plain = ("MedievalSoldier" in stem or "CivilianWorker" in stem or
             stem.startswith("Soldier_") or stem.endswith("_Feet"))
    if plain:
        image = bpy.data.images.new(f"T_{stem}_BaseColor", width=1024, height=1024, alpha=False)
        image.generated_color = tint
        image.filepath_raw = str(tex_path)
        image.file_format = "PNG"
        image.save()
        material = bpy.data.materials.new(f"M_{stem}_Plain")
        material.use_nodes = True
        bsdf = material.node_tree.nodes.get("Principled BSDF")
        node = material.node_tree.nodes.new("ShaderNodeTexImage")
        node.image = image
        material.node_tree.links.new(node.outputs["Color"], bsdf.inputs["Base Color"])
        bsdf.inputs["Roughness"].default_value = 0.58
        return (material,), tex_path, True

    # Hunyuan's autogenerated UVs leave white/smeared regions.  We replace them
    # with a planar front projection and stable back/sleeve materials.
    front = bpy.data.materials.new(f"M_{stem}_Front")
    front.use_nodes = True
    fbsdf = front.node_tree.nodes.get("Principled BSDF")
    ftex = front.node_tree.nodes.new("ShaderNodeTexImage")
    ftex.image = image
    front.node_tree.links.new(ftex.outputs["Color"], fbsdf.inputs["Base Color"])
    fbsdf.inputs["Roughness"].default_value = 0.54

    back = bpy.data.materials.new(f"M_{stem}_Back")
    back.use_nodes = True
    bbsdf = back.node_tree.nodes.get("Principled BSDF")
    bbsdf.inputs["Base Color"].default_value = tint
    bbsdf.inputs["Roughness"].default_value = 0.58

    sleeve = bpy.data.materials.new(f"M_{stem}_Sleeves")
    sleeve.use_nodes = True
    sbsdf = sleeve.node_tree.nodes.get("Principled BSDF")
    sbsdf.inputs["Base Color"].default_value = metal
    sbsdf.inputs["Metallic"].default_value = 0.35 if side == "Giltside" else 0.20
    sbsdf.inputs["Roughness"].default_value = 0.42
    return (front, back, sleeve), tex_path, False


def tri_count(obj):
    return sum(len(poly.vertices) - 2 for poly in obj.data.polygons)


def prepare(obj, stem, piece, materials, plain):
    target_longest, foot_z = PIECE_SETUP[piece]
    select_only(obj)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    coords = [v.co.copy() for v in obj.data.vertices]
    extents = [max(v[i] for v in coords) - min(v[i] for v in coords) for i in range(3)]
    scale = target_longest / max(extents) if max(extents) else 1.0
    for vert in obj.data.vertices:
        vert.co *= scale
    coords = [v.co for v in obj.data.vertices]
    min_z = min(v.z for v in coords)
    centre_x = (min(v.x for v in coords) + max(v.x for v in coords)) / 2.0
    centre_y = (min(v.y for v in coords) + max(v.y for v in coords)) / 2.0
    for vert in obj.data.vertices:
        vert.co.x -= centre_x
        vert.co.y -= centre_y
        vert.co.z += foot_z - min_z
    current = tri_count(obj)
    if current > 18000:
        modifier = obj.modifiers.new("TriangleBudget", "DECIMATE")
        modifier.decimate_type = "COLLAPSE"
        modifier.ratio = 18000.0 / current
        bpy.context.view_layer.objects.active = obj
        bpy.ops.object.modifier_apply(modifier=modifier.name)
    # Rebuild UV0 from object-space front projection; this avoids the broken
    # Hunyuan atlas that the fitter reported as white/smeared.
    uv = obj.data.uv_layers.get("UVMap") or obj.data.uv_layers.new(name="UVMap")
    xs = [v.co.x for v in obj.data.vertices]
    ys = [v.co.y for v in obj.data.vertices]
    zs = [v.co.z for v in obj.data.vertices]
    min_x, max_x = min(xs), max(xs)
    min_z, max_z = min(zs), max(zs)
    width, height = max(0.0001, max_x - min_x), max(0.0001, max_z - min_z)
    torso_half = width * 0.34
    obj.data.materials.clear()
    for material in materials:
        obj.data.materials.append(material)
    for poly in obj.data.polygons:
        centre = poly.center
        # Outer lateral regions are sleeves/boots; front-facing torso keeps the
        # generated art, while the reverse uses a matching unsmeared material.
        if plain:
            poly.material_index = 0
        elif piece == "Upper" and abs(centre.x) > torso_half:
            poly.material_index = 2
        elif poly.normal.y < -0.20:
            poly.material_index = 0
        else:
            poly.material_index = 1
        poly.use_smooth = True
        for loop_index in poly.loop_indices:
            vert = obj.data.vertices[obj.data.loops[loop_index].vertex_index].co
            uv.data[loop_index].uv = ((vert.x - min_x) / width, (vert.z - min_z) / height)
    obj.name = stem
    obj.data.name = f"{stem}_Mesh"
    # Origin remains at the invisible body's ground origin, +Z is up.
    obj.location = (0, 0, 0)


def export_one(side_dir, glb):
    stem = glb.stem
    piece = stem.rsplit("_", 1)[-1]
    if piece not in PIECE_SETUP:
        raise RuntimeError(f"Unrecognised clothing piece in {stem}")
    clear_scene()
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=str(glb))
    imported = [obj for obj in bpy.data.objects if obj not in before and obj.type == "MESH"]
    if not imported:
        raise RuntimeError(f"No mesh in {glb}")
    select_only(imported[0])
    for obj in imported[1:]:
        obj.select_set(True)
    if len(imported) > 1:
        bpy.ops.object.join()
    obj = bpy.context.view_layer.objects.active
    materials, texture, plain = make_materials(side_dir, stem)
    prepare(obj, stem, piece, materials, plain)
    output = side_dir / f"{stem}.fbx"
    select_only(obj)
    bpy.ops.export_scene.fbx(filepath=str(output), use_selection=True, object_types={"MESH"},
        global_scale=1.0, apply_unit_scale=True, apply_scale_options="FBX_SCALE_NONE",
        axis_forward="-Z", axis_up="Y", use_mesh_modifiers=True, mesh_smooth_type="FACE",
        bake_anim=False, path_mode="COPY", embed_textures=False)
    return output, texture, tri_count(obj)


def main():
    bpy.context.scene.unit_settings.system = "METRIC"
    bpy.context.scene.unit_settings.length_unit = "CENTIMETERS"
    completed = []
    for side_dir in sorted(path for path in ROOT.iterdir() if path.is_dir()):
        raw_dir = side_dir / "RawHunyuan"
        if not raw_dir.exists():
            continue
        for glb in sorted(raw_dir.glob("*.glb")):
            only_stem = os.environ.get("CLOTHING_STEM")
            if only_stem and glb.stem != only_stem:
                continue
            output, texture, triangles = export_one(side_dir, glb)
            completed.append((output, texture, triangles))
    existing = STATUS.read_text(encoding="utf-8") if STATUS.exists() else "# Clothing source status\n"
    with STATUS.open("a", encoding="utf-8") as handle:
        if not STATUS.exists() or not existing:
            handle.write("# Clothing source status\n")
        for output, texture, triangles in completed:
            entry = f"- `{output}` — Local Hunyuan3D-2 + Blender export; {BODY_REFERENCE}; {triangles} tris; 1K base-color texture `{texture}`\n"
            if str(output) not in existing:
                handle.write(entry)


if __name__ == "__main__":
    main()
