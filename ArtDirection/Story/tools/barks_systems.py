def merge(people):
    ids = {p["id"] for p in people}
    assert set(SYSTEM) == ids, (sorted(ids - set(SYSTEM)), sorted(set(SYSTEM) - ids))
    soldiers = {p["id"] for p in people if p["look_role"] == "Soldier"}
    assert set(SOLDIER) == soldiers, (sorted(soldiers - set(SOLDIER)), sorted(set(SOLDIER) - soldiers))
    for p in people:
        lines = SYSTEM[p["id"]]
        assert len(lines) == len(SYSTEM_KEYS), p["id"]
        p["barks"].update(dict(zip(SYSTEM_KEYS, lines)))
        if p["id"] in SOLDIER:
            p["barks"].update(dict(zip(SOLDIER_KEYS, SOLDIER[p["id"]])))
            p["barks"]["enemy_down"] = ENEMY_DOWN[p["id"]]
        if p["id"] in GEAR:
            p["look"]["gear"] = GEAR[p["id"]]
            p["look"]["tags"] += [f"Look_Gear_{g}" for g in GEAR[p["id"]]]
        if p["id"] in SHIELD_CLOTHING and "shield" not in p["look"]["clothing"]:
            p["look"]["clothing"] += SHIELD_CLOTHING[p["id"]]
